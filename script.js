function openLightbox(index) {
  state.currentPhoto = index;
  updateLightbox();
  lightbox.classList.add("open");
  lightbox.setAttribute("aria-hidden", "false");
}

function closeLightbox() {
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
}

function updateLightbox() {
  const photo = birthdayData.photos[state.currentPhoto];
  lightboxImage.alt = photo.caption;
  lightboxImage.onerror = () => handleImageFallback(lightboxImage, `Memory ${state.currentPhoto + 1}`);
  lightboxImage.src = photo.src;
  lightboxCaption.textContent = photo.caption;
}

function moveLightbox(direction) {
  const total = birthdayData.photos.length;
  state.currentPhoto = (state.currentPhoto + direction + total) % total;
  updateLightbox();
}

function startTypewriter() {
  if (state.letterStarted) return;
  state.letterStarted = true;
  const personalizedLetter = birthdayData.letter
    .replaceAll("[FRIEND NAME]", birthdayData.friendName)
    .replaceAll("[YOUR NAME]", birthdayData.yourName)
    .replaceAll("[Punam]", birthdayData.friendName)
    .replaceAll("[Soham]", birthdayData.yourName);
  let index = 0;
  const type = () => {
    letterText.textContent = personalizedLetter.slice(0, index);
    index += 1;
    if (index <= personalizedLetter.length) {
      window.setTimeout(type, index % 3 === 0 ? 18 : 9);
    }
  };
  type();
}

function revealOnScroll() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        if (entry.target.classList.contains("letter-paper")) {
          startTypewriter();
        }
      }
    });
  }, { threshold: 0.18 });

  $$(".reveal").forEach((node) => observer.observe(node));
}

function createFloatingSymbol(target, symbol, className, duration = 8) {
  const item = document.createElement("span");
  item.className = className;
  item.textContent = symbol;
  item.style.left = `${Math.random() * 100}%`;
  item.style.bottom = `-${Math.random() * 18 + 4}vh`;
  item.style.fontSize = `${Math.random() * 1.1 + 0.85}rem`;
  item.style.animationDuration = `${Math.random() * 4 + duration}s`;
  item.style.animationDelay = `${Math.random() * 1.2}s`;
  target.appendChild(item);
  window.setTimeout(() => item.remove(), (duration + 5) * 1000);
}

function startBackgroundFloaters() {
  const symbols = ["❤", "✦", "♡", "✨", "☆"];
  window.setInterval(() => {
    createFloatingSymbol(floatingLayer, symbols[Math.floor(Math.random() * symbols.length)], "float-item", 9);
  }, 620);
}

function burstConfetti(target, count = 80) {
  const colors = ["#f7b7d2", "#b8a1ff", "#ffd98c", "#fff9f5", "#7c5cfc"];
  for (let index = 0; index < count; index += 1) {
    const piece = document.createElement("span");
    piece.className = "confetti-piece";
    piece.style.left = `${Math.random() * 100}%`;
    piece.style.top = `${Math.random() * -20}vh`;
    piece.style.width = `${Math.random() * 0.45 + 0.32}rem`;
    piece.style.height = `${Math.random() * 0.9 + 0.45}rem`;
    piece.style.borderRadius = Math.random() > 0.5 ? "999px" : "2px";
    piece.style.background = colors[Math.floor(Math.random() * colors.length)];
    piece.style.animation = `fall ${Math.random() * 2.6 + 3}s linear forwards`;
    target.appendChild(piece);
    window.setTimeout(() => piece.remove(), 6200);
  }
}

function burstStars(target, count = 34) {
  for (let index = 0; index < count; index += 1) {
    createFloatingSymbol(target, Math.random() > 0.5 ? "✨" : "❤", "star-piece", 5);
  }
}

function openWebsite() {
  welcome.classList.add("hidden");
  siteContent.classList.add("visible");
  siteNav.classList.add("visible");
  menuToggle.classList.add("visible");
  musicToggle.classList.add("visible");
  document.body.classList.remove("locked");
  burstStars(floatingLayer, 20);
  startBackgroundFloaters();
}

function setupNavigation() {
  menuToggle.addEventListener("click", () => {
    siteNav.classList.toggle("open");
  });

  $$(".site-nav a").forEach((link) => {
    link.addEventListener("click", () => siteNav.classList.remove("open"));
  });

  const navObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      $$(".site-nav a").forEach((link) => {
        link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`);
      });
    });
  }, { threshold: 0.46 });

  $$(".section[id]").forEach((section) => navObserver.observe(section));
}

function setupMusic() {
  musicToggle.addEventListener("click", async () => {
    try {
      if (music.paused) {
        await music.play();
        state.musicPlaying = true;
      } else {
        music.pause();
        state.musicPlaying = false;
      }
    } catch {
      state.musicPlaying = false;
      musicToggle.textContent = "♪ Music unavailable";
      window.setTimeout(() => {
        musicToggle.textContent = "♪ Music Off";
      }, 2200);
      return;
    }
    musicToggle.textContent = state.musicPlaying ? "♪ Music On" : "♪ Music Off";
  });
}

