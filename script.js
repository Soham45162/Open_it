function handleImageFallback(img, label) {
  img.onerror = null;
  img.src = fallbackImageData(label);
}

function renderGallery() {
  gallery.innerHTML = birthdayData.photos.map((photo, index) => `
    <figure class="photo-card reveal" role="button" tabindex="0" aria-label="Open memory ${index + 1}: ${photo.caption}" style="--tilt: ${index % 2 ? "1.5deg" : "-1.5deg"}">
      <img src="${photo.src}" alt="${photo.caption}" loading="lazy" data-fallback="Memory ${index + 1}">
      <span class="photo-view">View memory</span>
      <figcaption>${photo.caption}</figcaption>
    </figure>
  `).join("");

  $$("#gallery img").forEach((img) => {
    img.addEventListener("error", () => handleImageFallback(img, img.dataset.fallback));
  });

  $$("#gallery .photo-card").forEach((card, index) => {
    card.addEventListener("click", () => openLightbox(index));
    card.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openLightbox(index);
      }
    });
  });
}

